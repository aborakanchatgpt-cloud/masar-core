"""
Masar Core — توحيد صيغة رقم الجوال — B9/A1.

المشكلة التي عولجت هنا: أحمد يسجّل عميلًا جديدًا ببوت الأدمن ويكتب الرقم
بصيغة محلية شائعة (05xxxxxxxx)، بينما زر "مشاركة رقم الجوال" بتيليجرام
يرسل الرقم من جهة اتصال حقيقية بصيغة دولية (966xxxxxxxxx أو +966...).
المطابقة القديمة كانت حرفية (WHERE phone = :phone) على أرقام مجردة
من كل شيء غير الأرقام — فلا تتطابق الصيغتان أبدًا، ويُخبر العميل بالخطأ أن لا
اشتراك مسجّل باسمه.

canonical_phone توحّد أي رقم سعودي محتمل لصيغة واحدة: 966xxxxxxxxx (12 رقمًا، بلا +). أرقام
غير سعودية أو غير قابلة للتوحيد تُعاد كأرقام مجردة كما كانت — لا رفض، فقط لا
تحسين (الحالة نادرة جدًا بسياق هذه الخدمة).
"""


def canonical_phone(raw: str) -> str:
    """يُرجع رقم الجوال بصيغة موحّدة 966xxxxxxxxx حيثما أمكن تحديدها،
    وإلا الأرقام المجردة فقط (السلوك القديم) كحل احتياطي آمن."""
    digits = "".join(ch for ch in (raw or "") if ch.isdigit())
    if not digits:
        return ""

    # 00966xxxxxxxxx → احذف صفري الشحن الدولي
    if digits.startswith("00") and len(digits) == 14 and digits[2:5] == "966":
        digits = digits[2:]

    # 0xxxxxxxxx (10 أرقام، يبدأ بصفر) → استبدل الصفر بـ966
    if len(digits) == 10 and digits.startswith("0"):
        digits = "966" + digits[1:]

    # xxxxxxxxx (9 أرقام تبدأ بـ5، بلا صفر ولا مفتاح دولة) → أضف 966
    elif len(digits) == 9 and digits.startswith("5"):
        digits = "966" + digits

    # 966xxxxxxxxx (12 رقمًا) → كما هي، صيغة مستهدفة بالفعل
    # أي طول/بادئة أخرى (رقم غير سعودي، أو رقم غير قابل للتفسير) → تُعاد كما
    # جُرّدت أعلاه بلا محاولة تخمين إضافية.

    return digits
